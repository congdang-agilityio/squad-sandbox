/** Reason phrase of an IANA-registered HTTP status code, or `undefined` for unknown codes. */
export function reasonPhrase(code: number, locale: Locale): string | undefined {
  if (!Object.hasOwn(PHRASES, code)) return undefined;
  return PHRASES[code][locale === 'vi' ? 1 : 0];
}
